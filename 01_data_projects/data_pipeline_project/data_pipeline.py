# Load datasets
url = 'https://archive.ics.uci.edu/ml/machine-learning-databases/wine-quality/winequality-white.csv'
df = pd.read_csv(url, sep=';')

url2 = 'https://archive.ics.uci.edu/ml/machine-learning-databases/wine-quality/winequality-red.csv'
df2 = pd.read_csv(url2, sep=';')

# Add wine type
df2['wine_type'] = 'red'
df['wine_type'] = 'white'

# Merge
wine = pd.concat([df2, df], axis=0, ignore_index=True)

# Drop wine_type column entirely (do not use it as a feature)
wine.drop('wine_type', axis=1, inplace=True)

# Define features and target
X = wine.drop('quality', axis=1)
y = wine['quality']

# Standardize features
scaler = StandardScaler()
