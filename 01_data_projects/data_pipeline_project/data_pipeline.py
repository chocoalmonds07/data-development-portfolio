"""# **Histograms per Independent Variable**"""

wine.hist(figsize=(15, 12), bins=30, edgecolor='black')

plt.suptitle("Histograms of Wine Quality Features", fontsize=16)
plt.tight_layout(rect=[0, 0, 1, 0.96])
plt.show()

"""## **Correlation Matrix & Heatmap**"""

corr_matrix = wine.corr()

plt.figure(figsize=(12, 10))
sns.heatmap(corr_matrix, annot=True, fmt=".2f", cmap="coolwarm", square=True)
plt.title("Correlation Heatmap of Wine Features")
plt.show()

"""## **Scatter Plots (All Variables vs. Quality)**"""

independent_vars = [col for col in wine.columns if col != 'quality']

for col in independent_vars:
    plt.figure(figsize=(6, 4))
    sns.scatterplot(x=col, y='quality', data=df, alpha=0.6)
    plt.title(f"{col} vs Quality")
    plt.xlabel(col)
    plt.ylabel("Quality")
    plt.grid(True)
    plt.tight_layout()
    plt.show()

"""## **Pairwise Scatterplots**"""

numeric_df = wine.select_dtypes(include=['number'])

